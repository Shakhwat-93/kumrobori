-- 1. Create orders table
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  address text not null,
  package_id text,
  product_name text not null,
  quantity integer not null default 1,
  unit text default 'কেজি',
  unit_price numeric not null,
  delivery_charge numeric not null default 0,
  total_price numeric not null,
  status text not null default 'pending', -- pending, confirmed, delivered, cancelled
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Enable Row Level Security (RLS)
alter table public.orders enable row level security;

-- 3. Policy: Allow customers (public) to insert new orders
drop policy if exists "Allow public to place orders" on public.orders;
create policy "Allow public to place orders" on public.orders
  for insert
  to anon, authenticated
  with check (true);

-- 4. Policy: Allow authenticated store admins to view and manage orders
drop policy if exists "Allow authenticated to view orders" on public.orders;
create policy "Allow authenticated to view orders" on public.orders
  for select
  to authenticated
  using (true);

drop policy if exists "Allow authenticated to update orders" on public.orders;
create policy "Allow authenticated to update orders" on public.orders
  for update
  to authenticated
  using (true);
