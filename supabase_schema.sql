-- 1. Create orders table
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_id text,
  name text not null,
  phone text not null,
  address text not null,
  package_id text,
  product_name text not null,
  package_name text,
  quantity integer not null default 1,
  unit text default 'কেজি',
  unit_price numeric not null,
  subtotal numeric,
  delivery_charge numeric not null default 0,
  delivery_fee numeric default 0,
  discount numeric default 0,
  total_price numeric not null,
  payment_method text default 'cod',
  items jsonb default '[]'::jsonb,
  ip_address text,
  area text default 'inside_dhaka',
  notes text,
  status text not null default 'pending', -- pending, confirmed, delivered, cancelled
  courier_check_id bigint,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default now()
);

-- 2. Enable Row Level Security (RLS)
alter table public.orders enable row level security;

-- 3. Policies for orders
drop policy if exists "Allow public to place orders" on public.orders;
create policy "Allow public to place orders" on public.orders
  for insert to anon, authenticated, public
  with check (true);

drop policy if exists "Allow public select on orders" on public.orders;
create policy "Allow public select on orders" on public.orders
  for select to public
  using (true);

drop policy if exists "Allow public update on orders" on public.orders;
create policy "Allow public update on orders" on public.orders
  for update to public
  using (true);

drop policy if exists "Allow public delete on orders" on public.orders;
create policy "Allow public delete on orders" on public.orders
  for delete to public
  using (true);

-- 4. Enable Supabase Realtime for orders
alter publication supabase_realtime add table public.orders;

-- 5. BD Courier atomic claim function
create or replace function public.claim_courier_check(p_phone text)
returns jsonb
language plpgsql
security definer
as $$
declare
  v_record public.bdcourier_checks%ROWTYPE;
begin
  select * into v_record
  from public.bdcourier_checks
  where phone = p_phone
  for update;

  if found then
    if v_record.status = 'completed' then
      return jsonb_build_object('claimed', false, 'record', to_jsonb(v_record));
    end if;

    if v_record.status = 'pending' and v_record.claimed_at > (now() - interval '60 seconds') then
      return jsonb_build_object('claimed', false, 'record', to_jsonb(v_record));
    end if;

    update public.bdcourier_checks
    set status = 'pending',
        claimed_at = now(),
        attempt_count = coalesce(attempt_count, 0) + 1,
        updated_at = now()
    where id = v_record.id
    returning * into v_record;

    return jsonb_build_object('claimed', true, 'record', to_jsonb(v_record));
  else
    insert into public.bdcourier_checks (phone, status, claimed_at, attempt_count)
    values (p_phone, 'pending', now(), 1)
    returning * into v_record;

    return jsonb_build_object('claimed', true, 'record', to_jsonb(v_record));
  end if;
end;
$$;

grant execute on function public.claim_courier_check(text) to anon, authenticated, service_role, public;
